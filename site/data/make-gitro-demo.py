#!/usr/bin/env python3
"""Writes gitro-demo.js, the recorded session that the Run page plays when no companion is connected.

Every answer is real gitro output from this jigs clone, so the demo can't show anything gitro doesn't do.
Run it again after changing gitro, and before publishing the site:

    python3 site/data/make-gitro-demo.py

Needs bash and git on PATH (from Git Bash on Windows).
"""

import datetime
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
JIGS = os.path.dirname(os.path.dirname(HERE))
GITRO = os.path.join(JIGS, 'bash', 'functions', 'gitro.sh')
OUTPUT = os.path.join(HERE, 'gitro-demo.js')

# What the demo's outside caller asks, in order: a reviewer finding their way around, then two requests gitro refuses.
CALLER = [
    'status --short --branch',
    'log --oneline -8',
    'show --stat --oneline HEAD',
    'diff --stat',
    'grep -n _gitro_flag_allowed -- bash/functions/gitro.sh',
    'branch -d main',
    'diff --output=notes.txt',
    'diff ../../.ssh/id_ed25519 README.md',
]

# The Run page's suggested requests, which the demo also answers.
SUGGESTED = ['status --short --branch', 'log --oneline -10', 'diff --stat', 'diff --cached --stat', 'branch -vv']

# Example paths shown in the demo instead of this machine's.
REPO = '~/Repos/jigs'
DIR = '~/Exchange/jigs'


def main():
    # On Windows, a bare 'bash' can start WSL's bash from System32, so bash is looked up on PATH.
    bash = shutil.which('bash')
    if not bash:
        sys.exit('bash is not on PATH.')

    def gitro(request):
        result = subprocess.run([bash, GITRO, '-C', JIGS] + request.split(' '),
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        output = result.stdout.decode('utf-8', 'replace').replace('\r\n', '\n')
        for form in {JIGS, JIGS.replace('\\', '/')}:
            output = output.replace(form, REPO)
        return {'exit': result.returncode, 'response': '# gitro exit=%d: %s\n%s' % (result.returncode, request, output)}

    head = gitro('rev-parse --short HEAD')['response'].split('\n')[1].strip()
    data = {
        'recorded': '%s at %s' % (datetime.date.today().isoformat(), head),
        'repo': REPO,
        'dir': DIR,
        'serving': "gitro: serving 'jigs' (%s) from %s, keeping responses in %s/kept (Ctrl+C stops)" % (REPO, DIR, DIR),
        'caller': CALLER,
        'answers': {request: gitro(request) for request in dict.fromkeys(CALLER + SUGGESTED)},
    }
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as script:
        script.write('/* Generated by make-gitro-demo.py from the jigs repository: real gitro answers for the Run page\'s demo.\n'
                     '   Run that script again rather than editing this file. */\n')
        script.write('window.JIGS_GITRO_DEMO = %s;\n' % json.dumps(data, indent=1, ensure_ascii=False))
    print('wrote %s (%d answers, recorded %s)' % (OUTPUT, len(data['answers']), data['recorded']))


if __name__ == '__main__':
    main()
