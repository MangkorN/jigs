#!/usr/bin/env python3
"""Writes the README's tool list and the site's docs data from docs/, where each tool is documented once.

Each page in docs/ starts with '# <name>', a blank line, and a paragraph that summarizes the tool.
That paragraph becomes the tool's line in the README, between its tools:start and tools:end markers,
and its summary on the site, which also gets the whole page, in site/data/docs.js.

    python3 site/data/make-docs.py           write both
    python3 site/data/make-docs.py --check   write nothing, and exit with 1 if either is out of date
"""

import argparse
import json
import os
import re
import sys

JIGS_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(JIGS_ROOT, 'docs')
README = os.path.join(JIGS_ROOT, 'README.md')
OUTPUT = os.path.join(JIGS_ROOT, 'site', 'data', 'docs.js')

# The order of the tools in the README and on the site. Pages not named here follow, sorted by name.
ORDER = ['lsf', 'catcs', 'toclip', 'csbundle', 'csapply', 'gdm', 'gitro', 'vs-tabs']

START = '<!-- tools:start'
END = '<!-- tools:end -->'
START_LINE = '<!-- tools:start: written by site/data/make-docs.py from docs/, so edit those pages, then run it -->'

PAGE = re.compile(r'# (?P<title>[^\n]+)\n\n(?P<summary>(?:[^\n]+\n)+)')


def read(path):
    with open(path, encoding='utf-8', newline='') as source:
        return source.read()


def read_page(name):
    """A page's name, title, summary as one line, and its text after the title."""
    path = os.path.join(DOCS, name + '.md')
    text = read(path).replace('\r\n', '\n')
    match = PAGE.match(text)
    if not match or match.group('summary').startswith(('#', '```', '- ', '|', '>')):
        sys.exit('%s must start with "# <name>", a blank line, then a paragraph summarizing the tool.' % path)
    summary = ' '.join(line.strip() for line in match.group('summary').splitlines())
    body = text[len('# ' + match.group('title')) + 1:].strip('\n') + '\n'
    return {'id': name, 'title': match.group('title').strip(), 'summary': summary, 'markdown': body}


def page_names():
    found = sorted(name[:-3] for name in os.listdir(DOCS) if name.endswith('.md'))
    return [name for name in ORDER if name in found] + [name for name in found if name not in ORDER]


def readme_text(current, pages):
    """The README with the lines between its markers replaced by one line per tool."""
    lines = current.replace('\r\n', '\n').split('\n')
    starts = [i for i, line in enumerate(lines) if line.startswith(START)]
    ends = [i for i, line in enumerate(lines) if line == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        sys.exit('README.md needs one line starting with "%s" and, after it, one "%s".' % (START, END))
    items = ['- **[%s](docs/%s.md):** %s' % (page['title'], page['id'], page['summary']) for page in pages]
    return '\n'.join(lines[:starts[0]] + [START_LINE] + items + lines[ends[0]:])


def docs_text(pages):
    return ('/* Generated by make-docs.py from docs/: every tool\'s page for the site. Run it again rather than editing this file. */\n'
            'window.JIGS_DOCS = %s;\n' % json.dumps(pages, indent=1))


def same(path, text):
    """Whether the file holds this text, whichever line endings it was checked out with."""
    return os.path.isfile(path) and read(path).replace('\r\n', '\n') == text


def write(path, text):
    """Writes the text with the line endings the file already has, so a CRLF checkout stays CRLF."""
    crlf = os.path.isfile(path) and '\r\n' in read(path)
    with open(path, 'w', encoding='utf-8', newline='') as target:
        target.write(text.replace('\n', '\r\n') if crlf else text)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='write nothing, and exit with 1 if either output is out of date')
    args = parser.parse_args()

    pages = [read_page(name) for name in page_names()]
    outputs = [(README, readme_text(read(README), pages)), (OUTPUT, docs_text(pages))]
    stale = [path for path, text in outputs if not same(path, text)]
    if args.check:
        for path in stale:
            print('%s is out of date. Run python3 site/data/make-docs.py.' % os.path.relpath(path, JIGS_ROOT))
        sys.exit(1 if stale else 0)
    for path, text in outputs:
        if path in stale:
            write(path, text)
            print('wrote ' + os.path.relpath(path, JIGS_ROOT))
    if not stale:
        print('README.md and site/data/docs.js are up to date.')


if __name__ == '__main__':
    main()
